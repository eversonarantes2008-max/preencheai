// Master PDF buffer in-memory cache
const cachedMasterPdfs: Record<string, Uint8Array> = {};

export async function getMasterPdfBytes(template: DocumentTemplate): Promise<Uint8Array> {
  const templateId = template.id;

  // If template has an embedded original PDF file (from upload), always use it directly
  if (template.file_url && template.file_url.startsWith('data:application/pdf;base64,')) {
    try {
      const base64Data = template.file_url.split(',')[1];
      const binaryString = atob(base64Data);
      const len = binaryString.length;
      const b = new Uint8Array(len);
      for (let i = 0; i < len; i++) {
        b[i] = binaryString.charCodeAt(i);
      }
      return b;
    } catch (e) {
      console.warn('Error parsing base64 PDF from template file_url:', e);
    }
  }

  if (cachedMasterPdfs[templateId]) {
    return cachedMasterPdfs[templateId];
  }

  let bytes: Uint8Array;

  switch (templateId) {
    case 'template_autorizacao_pagamento':
      bytes = await generateMasterAutorizacaoPagamentoPdf();
      break;
    case 'template_termo_responsabilidade':
      bytes = await generateMasterResponsabilidadePdf();
      break;
    case 'template_comodato_veiculo':
      bytes = await generateMasterComodatoVeiculoPdf();
      break;
    case 'template_carta_cancelamento':
      bytes = await generateMasterCartaCancelamentoPdf();
      break;
    case 'template_dacao_pagamento':
      bytes = await generateMasterDacaoPagamentoPdf();
      break;
    case 'template_isencao_nf_servicos':
      bytes = await generateMasterIsencaoNfPdf();
      break;
    case 'template_termo_compra_usado_gwm':
      bytes = await generateMasterTermoCompraUsadoGwmPdf();
      break;
    case 'template_formulario_devolucao':
      bytes = await generateMasterFormularioDevolucaoPdf();
      break;
    default:
      bytes = await generateMasterResponsabilidadePdf();
      break;
  }

  cachedMasterPdfs[templateId] = bytes;
  return bytes;
}

// Storage Utilities
export function loadAllTemplates(): DocumentTemplate[] {
  try {
    const raw = localStorage.getItem(TEMPLATES_STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(TEMPLATES_STORAGE_KEY, JSON.stringify(ALL_BUILT_IN_TEMPLATES));
      return ALL_BUILT_IN_TEMPLATES;
    }
    const parsed: DocumentTemplate[] = JSON.parse(raw);
    let changed = false;

    // Ensure all built-in templates exist and are updated
    for (const builtIn of ALL_BUILT_IN_TEMPLATES) {
      const idx = parsed.findIndex((t) => t.id === builtIn.id);
      if (idx >= 0) {
        if (parsed[idx].version !== CURRENT_TEMPLATE_VERSION || (parsed[idx].fields || []).length !== builtIn.fields.length) {
          parsed[idx] = builtIn;
          changed = true;
        }
      } else {
        parsed.push(builtIn);
        changed = true;
      }
    }

    if (changed) {
      localStorage.setItem(TEMPLATES_STORAGE_KEY, JSON.stringify(parsed));
    }

    return parsed;
  } catch {
    return ALL_BUILT_IN_TEMPLATES;
  }
}

export function saveTemplate(template: DocumentTemplate): void {
  const all = loadAllTemplates();
  const index = all.findIndex((t) => t.id === template.id);
  if (index >= 0) {
    all[index] = { ...template, updated_at: new Date().toISOString() };
  } else {
    all.push({
      ...template,
      created_at: template.created_at || new Date().toISOString(),
      updated_at: new Date().toISOString(),
    });
  }
  localStorage.setItem(TEMPLATES_STORAGE_KEY, JSON.stringify(all));
}

export function deleteTemplate(templateId: string): void {
  const all = loadAllTemplates().filter((t) => t.id !== templateId && !t.is_built_in);
  localStorage.setItem(TEMPLATES_STORAGE_KEY, JSON.stringify(all));
}

export function loadDocumentHistory(): GeneratedDocument[] {
  try {
    const raw = localStorage.getItem(HISTORY_STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function saveDocumentToHistory(doc: GeneratedDocument): void {
  const history = loadDocumentHistory();
  history.unshift(doc);
  if (history.length > 50) history.pop();
  localStorage.setItem(HISTORY_STORAGE_KEY, JSON.stringify(history));
}

export function deleteDocumentFromHistory(docId: string): void {
  const history = loadDocumentHistory().filter((d) => d.id !== docId);
  localStorage.setItem(HISTORY_STORAGE_KEY, JSON.stringify(history));
}

export function clearAllDocumentHistory(): void {
  localStorage.removeItem(HISTORY_STORAGE_KEY);
}
